const regionByCode = new Map(DOMESTIC_REGIONS.map((region) => [region.code, region]))

export const DOMESTIC_CITIES: DomesticCityOption[] = domesticCityRows.flatMap(([cityName, regionCode]) => {
  const region = regionByCode.get(regionCode)
  return region ? [{ cityName, regionCode, regionName: region.mapName, regionLabel: region.name }] : []
})

export const DOMESTIC_CITY_SUGGESTIONS = DOMESTIC_CITIES.slice(0, 8)

const normalize = (value: string) => value.trim().toLocaleLowerCase().replaceAll(' ', '')

export function getDomesticCities(keyword: string) {
  const query = normalize(keyword)
  return DOMESTIC_CITIES.filter((city) =>
    !query || [city.cityName, city.regionName, city.regionLabel].some((value) => normalize(value).includes(query)),
  )
}
